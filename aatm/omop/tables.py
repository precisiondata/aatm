"""Pydantic models for OMOP CDM tables built from extracted entities.

These models describe rows of the OMOP CDM v5.5 tables that `aatm.omop.builder`
fills from extracted entities. Every field is optional, because rows built from
clinical notes are usually incomplete: identifiers such as `person_id` come from other
sources. The fields the CDM requires are listed in `required_fields`, and the builder
reports the ones it could not fill.

See https://ohdsi.github.io/CommonDataModel/cdm55.html
"""

from datetime import date, datetime
from typing import Annotated, ClassVar, Optional

from pydantic import BaseModel, ConfigDict, Field, StringConstraints

_Varchar50 = Annotated[str, StringConstraints(max_length=50)]


class OmopTableRow(BaseModel):
    """Base class for a (possibly partial) row of an OMOP CDM table.

    Class attributes:
        table_name: The CDM table name, e.g. ``"measurement"``.
        primary_key: The primary key column, generated by the builder.
        required_fields: Columns the CDM requires. Missing ones are reported.
        concept_domains: Expected domain of the concept stored in some ``*_concept_id``
            columns, checked when the builder is created.
        excluded_concept_domains: Domains a column must not hold, e.g. a Condition
            concept in ``observation_concept_id`` belongs to ``condition_occurrence``.
        date_ranges: Pairs of (start, end) columns where the end cannot come before
            the start. The builder drops an end that does and reports it.
    """

    model_config = ConfigDict(extra="forbid")

    table_name: ClassVar[str]
    primary_key: ClassVar[str]
    required_fields: ClassVar[tuple[str, ...]]
    concept_domains: ClassVar[dict[str, str]] = {}
    excluded_concept_domains: ClassVar[dict[str, frozenset[str]]] = {}
    date_ranges: ClassVar[tuple[tuple[str, str], ...]] = ()

    @classmethod
    def domain_problem(cls, column: str, domain_id: Optional[str]) -> Optional[str]:
        """Why a concept of `domain_id` cannot go in `column`, or ``None`` if it can.

        The reason reads after "is", e.g. "in the 'Observation' domain, not 'Measurement'".
        """
        expected = cls.concept_domains.get(column)
        if expected and domain_id != expected:
            return f"in the {domain_id!r} domain, not {expected!r}"
        excluded = cls.excluded_concept_domains.get(column, frozenset())
        if domain_id in excluded:
            return (
                f"in the {domain_id!r} domain, which goes to another table than "
                f"{cls.table_name!r}"
            )
        return None


class Measurement(OmopTableRow):
    """A row of the OMOP CDM v5.5 ``measurement`` table.

    Measurements are attribute-value pairs: `measurement_concept_id` is the attribute
    (e.g. the ECOG performance status score) and the value is a number
    (`value_as_number`, with `unit_concept_id`) and/or a concept (`value_as_concept_id`).
    """

    table_name: ClassVar[str] = "measurement"
    primary_key: ClassVar[str] = "measurement_id"
    required_fields: ClassVar[tuple[str, ...]] = (
        "measurement_id",
        "person_id",
        "measurement_concept_id",
        "measurement_date",
        "measurement_type_concept_id",
    )
    concept_domains: ClassVar[dict[str, str]] = {
        "measurement_concept_id": "Measurement",
        "measurement_type_concept_id": "Type Concept",
        "operator_concept_id": "Meas Value Operator",
        "unit_concept_id": "Unit",
    }

    measurement_id: Optional[int] = None
    person_id: Optional[int] = None
    measurement_concept_id: Optional[int] = None
    measurement_date: Optional[date] = None
    measurement_datetime: Optional[datetime] = None
    measurement_time: Optional[Annotated[str, StringConstraints(max_length=10)]] = None
    measurement_type_concept_id: Optional[int] = None
    operator_concept_id: Optional[int] = None
    value_as_number: Optional[float] = None
    value_as_concept_id: Optional[int] = None
    unit_concept_id: Optional[int] = None
    range_low: Optional[float] = None
    range_high: Optional[float] = None
    provider_id: Optional[int] = None
    visit_occurrence_id: Optional[int] = None
    visit_detail_id: Optional[int] = None
    measurement_source_value: Optional[_Varchar50] = None
    measurement_source_concept_id: Optional[int] = None
    unit_source_value: Optional[_Varchar50] = None
    unit_source_concept_id: Optional[int] = None
    value_source_value: Optional[_Varchar50] = None
    value_as_source_concept_id: Optional[int] = None
    measurement_event_id: Optional[int] = None
    meas_event_field_concept_id: Optional[int] = None


class Observation(OmopTableRow):
    """A row of the OMOP CDM v5.5 ``observation`` table.

    Clinical facts that are not measurements, conditions, procedures, drugs or devices:
    social and lifestyle facts (smoking), medical and family history, and the like.
    Like measurements, they are attribute-value pairs: `observation_concept_id` is the
    attribute and the value is a concept, a number, a string or a date. For family
    history, `observation_concept_id` is the history concept and `value_as_concept_id`
    the condition.
    """

    table_name: ClassVar[str] = "observation"
    primary_key: ClassVar[str] = "observation_id"
    required_fields: ClassVar[tuple[str, ...]] = (
        "observation_id",
        "person_id",
        "observation_concept_id",
        "observation_date",
        "observation_type_concept_id",
    )
    concept_domains: ClassVar[dict[str, str]] = {
        "observation_type_concept_id": "Type Concept",
        "unit_concept_id": "Unit",
    }
    # "Concepts from the Condition, Procedure, Drug, Measurement or Device domains must
    # go to their own tables" (CDM v5.5 conventions for observation_concept_id).
    excluded_concept_domains: ClassVar[dict[str, frozenset[str]]] = {
        "observation_concept_id": frozenset(
            {"Condition", "Procedure", "Drug", "Measurement", "Device", "Specimen"}
        ),
    }

    observation_id: Optional[int] = None
    person_id: Optional[int] = None
    observation_concept_id: Optional[int] = None
    observation_date: Optional[date] = None
    observation_datetime: Optional[datetime] = None
    observation_type_concept_id: Optional[int] = None
    value_as_number: Optional[float] = None
    value_as_string: Optional[Annotated[str, StringConstraints(max_length=60)]] = None
    value_as_concept_id: Optional[int] = None
    value_as_date: Optional[date] = None
    qualifier_concept_id: Optional[int] = None
    unit_concept_id: Optional[int] = None
    provider_id: Optional[int] = None
    visit_occurrence_id: Optional[int] = None
    visit_detail_id: Optional[int] = None
    observation_source_value: Optional[_Varchar50] = None
    observation_source_concept_id: Optional[int] = None
    unit_source_value: Optional[_Varchar50] = None
    unit_source_concept_id: Optional[int] = None
    qualifier_source_value: Optional[_Varchar50] = None
    value_source_value: Optional[_Varchar50] = None
    value_as_source_concept_id: Optional[int] = None
    observation_event_id: Optional[int] = None
    obs_event_field_concept_id: Optional[int] = None


class ConditionOccurrence(OmopTableRow):
    """A row of the OMOP CDM v5.5 ``condition_occurrence`` table.

    Diagnoses, signs and symptoms of the patient. `condition_concept_id` is a standard
    concept of the Condition domain, and `condition_status_concept_id` qualifies the
    diagnosis, e.g. *Preliminary diagnosis*. Past diagnoses and conditions of relatives
    go to ``observation``.
    """

    table_name: ClassVar[str] = "condition_occurrence"
    primary_key: ClassVar[str] = "condition_occurrence_id"
    required_fields: ClassVar[tuple[str, ...]] = (
        "condition_occurrence_id",
        "person_id",
        "condition_concept_id",
        "condition_start_date",
        "condition_type_concept_id",
    )
    concept_domains: ClassVar[dict[str, str]] = {
        "condition_concept_id": "Condition",
        "condition_type_concept_id": "Type Concept",
        "condition_status_concept_id": "Condition Status",
    }
    date_ranges: ClassVar[tuple[tuple[str, str], ...]] = (
        ("condition_start_date", "condition_end_date"),
        ("condition_start_datetime", "condition_end_datetime"),
    )

    condition_occurrence_id: Optional[int] = None
    person_id: Optional[int] = None
    condition_concept_id: Optional[int] = None
    condition_start_date: Optional[date] = None
    condition_start_datetime: Optional[datetime] = None
    condition_end_date: Optional[date] = None
    condition_end_datetime: Optional[datetime] = None
    condition_type_concept_id: Optional[int] = None
    condition_status_concept_id: Optional[int] = None
    stop_reason: Optional[Annotated[str, StringConstraints(max_length=20)]] = None
    provider_id: Optional[int] = None
    visit_occurrence_id: Optional[int] = None
    visit_detail_id: Optional[int] = None
    condition_source_value: Optional[_Varchar50] = None
    condition_source_concept_id: Optional[int] = None
    condition_status_source_value: Optional[_Varchar50] = None


class DrugExposure(OmopTableRow):
    """A row of the OMOP CDM v5.5 ``drug_exposure`` table.

    A drug prescribed, administered or taken by the patient: medicines, vaccines and
    biologics. `drug_concept_id` is a standard concept of the Drug domain, as detailed
    as the source allows (a clinical drug such as "metformin 500 mg oral tablet" rather
    than the ingredient). `drug_exposure_end_date` is required: when the source has no
    end date, it is inferred (see the THEMIS conventions).
    """

    table_name: ClassVar[str] = "drug_exposure"
    primary_key: ClassVar[str] = "drug_exposure_id"
    required_fields: ClassVar[tuple[str, ...]] = (
        "drug_exposure_id",
        "person_id",
        "drug_concept_id",
        "drug_exposure_start_date",
        "drug_exposure_end_date",
        "drug_type_concept_id",
    )
    concept_domains: ClassVar[dict[str, str]] = {
        "drug_concept_id": "Drug",
        "drug_type_concept_id": "Type Concept",
        "route_concept_id": "Route",
    }
    date_ranges: ClassVar[tuple[tuple[str, str], ...]] = (
        ("drug_exposure_start_date", "drug_exposure_end_date"),
        ("drug_exposure_start_datetime", "drug_exposure_end_datetime"),
    )

    drug_exposure_id: Optional[int] = None
    person_id: Optional[int] = None
    drug_concept_id: Optional[int] = None
    drug_exposure_start_date: Optional[date] = None
    drug_exposure_start_datetime: Optional[datetime] = None
    drug_exposure_end_date: Optional[date] = None
    drug_exposure_end_datetime: Optional[datetime] = None
    verbatim_end_date: Optional[date] = None
    drug_type_concept_id: Optional[int] = None
    stop_reason: Optional[Annotated[str, StringConstraints(max_length=20)]] = None
    refills: Optional[Annotated[int, Field(ge=0)]] = None
    quantity: Optional[Annotated[float, Field(ge=0)]] = None
    # "Negative values are not allowed" (CDM v5.5 conventions for days_supply).
    days_supply: Optional[Annotated[int, Field(ge=0)]] = None
    sig: Optional[str] = None
    route_concept_id: Optional[int] = None
    lot_number: Optional[_Varchar50] = None
    provider_id: Optional[int] = None
    visit_occurrence_id: Optional[int] = None
    visit_detail_id: Optional[int] = None
    drug_source_value: Optional[_Varchar50] = None
    drug_source_concept_id: Optional[int] = None
    route_source_value: Optional[_Varchar50] = None
    dose_unit_source_value: Optional[_Varchar50] = None


OMOP_TABLES: dict[str, type[OmopTableRow]] = {
    model.table_name: model
    for model in (Measurement, Observation, ConditionOccurrence, DrugExposure)
}
