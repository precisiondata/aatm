"""Pydantic models for OMOP CDM tables built from extracted entities.

These models describe rows of the OMOP CDM v5.5 tables that `aatm.omop.builder`
fills from extracted entities. Every field is optional, because rows built from
clinical notes are usually incomplete: identifiers such as `person_id` come from other
sources. The fields the CDM requires are listed in `required_fields`, and the builder
reports the ones it could not fill.

See https://ohdsi.github.io/CommonDataModel/cdm55.html
"""

from datetime import date, datetime
from typing import Annotated, ClassVar, Optional

from pydantic import BaseModel, ConfigDict, StringConstraints

_Varchar50 = Annotated[str, StringConstraints(max_length=50)]


class OmopTableRow(BaseModel):
    """Base class for a (possibly partial) row of an OMOP CDM table.

    Class attributes:
        table_name: The CDM table name, e.g. ``"measurement"``.
        primary_key: The primary key column, generated by the builder.
        required_fields: Columns the CDM requires. Missing ones are reported.
        concept_domains: Expected domain of the concept stored in some ``*_concept_id``
            columns, checked when the builder is created.
    """

    model_config = ConfigDict(extra="forbid")

    table_name: ClassVar[str]
    primary_key: ClassVar[str]
    required_fields: ClassVar[tuple[str, ...]]
    concept_domains: ClassVar[dict[str, str]] = {}


class Measurement(OmopTableRow):
    """A row of the OMOP CDM v5.5 ``measurement`` table.

    Measurements are attribute-value pairs: `measurement_concept_id` is the attribute
    (e.g. the ECOG performance status score) and the value is a number
    (`value_as_number`, with `unit_concept_id`) and/or a concept (`value_as_concept_id`).
    """

    table_name: ClassVar[str] = "measurement"
    primary_key: ClassVar[str] = "measurement_id"
    required_fields: ClassVar[tuple[str, ...]] = (
        "measurement_id",
        "person_id",
        "measurement_concept_id",
        "measurement_date",
        "measurement_type_concept_id",
    )
    concept_domains: ClassVar[dict[str, str]] = {
        "measurement_concept_id": "Measurement",
        "measurement_type_concept_id": "Type Concept",
        "operator_concept_id": "Meas Value Operator",
        "unit_concept_id": "Unit",
    }

    measurement_id: Optional[int] = None
    person_id: Optional[int] = None
    measurement_concept_id: Optional[int] = None
    measurement_date: Optional[date] = None
    measurement_datetime: Optional[datetime] = None
    measurement_time: Optional[Annotated[str, StringConstraints(max_length=10)]] = None
    measurement_type_concept_id: Optional[int] = None
    operator_concept_id: Optional[int] = None
    value_as_number: Optional[float] = None
    value_as_concept_id: Optional[int] = None
    unit_concept_id: Optional[int] = None
    range_low: Optional[float] = None
    range_high: Optional[float] = None
    provider_id: Optional[int] = None
    visit_occurrence_id: Optional[int] = None
    visit_detail_id: Optional[int] = None
    measurement_source_value: Optional[_Varchar50] = None
    measurement_source_concept_id: Optional[int] = None
    unit_source_value: Optional[_Varchar50] = None
    unit_source_concept_id: Optional[int] = None
    value_source_value: Optional[_Varchar50] = None
    value_as_source_concept_id: Optional[int] = None
    measurement_event_id: Optional[int] = None
    meas_event_field_concept_id: Optional[int] = None


OMOP_TABLES: dict[str, type[OmopTableRow]] = {
    model.table_name: model for model in (Measurement,)
}
